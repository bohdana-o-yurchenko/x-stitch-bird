import { UA_BLUE, UA_YELLOW } from "../../flag";
import { isMajorLine, majorOffset, rulerLabels } from "../../grid/numbering";
import type { Pattern, Rect } from "../../pattern/types";
import { textWidth, type PdfPage } from "./pdfWriter";

/** What both chart PDFs share (SPEC §15.10): A4 portrait in points, the grid and its numbers, English labels. */
export const PAGE: PageBox = { w: 595.28, h: 841.89, left: 42, right: 26, top: 58, bottom: 34 };

/** A page and its margins, in points. */
export interface PageBox {
  w: number;
  h: number;
  left: number;
  right: number;
  top: number;
  bottom: number;
}

/** One page's part of the chart, numbered from 1. */
export interface Tile extends Rect {
  n: number;
}

/** Thin lines between cells, heavy ones every 10 following the chart's numbering (§15.2), and a border. */
export function drawGrid(page: PdfPage, p: Pattern, t: Rect, cell: number, ox: number, oy: number) {
  const size = { w: p.w, h: p.h }, mx = majorOffset(p.grid, "x", size), my = majorOffset(p.grid, "y", size);
  const minor: [number, number, number, number][] = [], major: [number, number, number, number][] = [];
  const right = ox + t.w * cell, bottom = oy + t.h * cell;
  for (let i = 0; i <= t.w; i++) (isMajorLine(t.x + i, mx) ? major : minor).push([ox + i * cell, oy, ox + i * cell, bottom]);
  for (let j = 0; j <= t.h; j++) (isMajorLine(t.y + j, my) ? major : minor).push([ox, oy + j * cell, right, oy + j * cell]);
  page.lines(minor, 0.3, 0.55);
  page.lines(major, 0.9, 0);
  page.rect(ox, oy, t.w * cell, t.h * cell, { stroke: 0, width: 1.1 });
}

/** Column numbers above and row numbers left of the grid, every 10 as on the chart's rulers. */
export function drawRulers(page: PdfPage, p: Pattern, t: Rect, cell: number, ox: number, oy: number) {
  const size = { w: p.w, h: p.h };
  for (const l of rulerLabels(p.grid, "x", size, 10)) if (l.at >= t.x && l.at <= t.x + t.w) page.text("regular", 7, ox + (l.at - t.x) * cell, oy - 4, String(l.text), "centre", 0.3);
  for (const l of rulerLabels(p.grid, "y", size, 10)) if (l.at >= t.y && l.at <= t.y + t.h) page.text("regular", 7, ox - 4, oy + (l.at - t.y) * cell + 2.5, String(l.text), "right", 0.3);
}

/** The app's name, as in its logo. */
export const APP_NAME = "пташечка";
/** The app in English (the bare address opens it in Ukrainian); the Pattern Keeper PDF, always English, links here. */
export const APP_URL_EN = "https://www.x-stitch-bird.app/en";

/**
 * The footer of every page: "Generated by пташечка · https://…", the name in bold and the address a link. `text` has
 * `{app}` and `{url}` where they go (a translated "Generated by {app} · {url}").
 */
export function drawFooter(page: PdfPage, text: string, url: string, glory: string, box: PageBox = PAGE, pageNo?: string) {
  const size = 7.5, y = box.h - 14;
  let x = box.left;
  // the page of the whole file, at the right
  if (pageNo) page.text("regular", 8, box.w - box.right, y, pageNo, "right", 0.3);
  for (const part of `${text} · ${glory} `.split(/(\{app\}|\{url\})/)) {
    if (!part) continue;
    const shown = part === "{app}" ? APP_NAME : part === "{url}" ? url : part, font = part === "{app}" ? "bold" : "regular";
    page.text(font, size, x, y, shown, "left", 0.45);
    const w = textWidth(shown, size, font);
    if (part === "{url}") page.link(x, y - size, w, size + 2, url);
    x += w;
  }
  // the Ukrainian flag, drawn: the text fonts have no emoji
  page.rects([[x, y - 6, 9, 3]], UA_BLUE);
  page.rects([[x, y - 3, 9, 3]], UA_YELLOW);
}

/** Cut short with … to fit `max` points. */
export function fitText(text: string, size: number, max: number, font: "regular" | "bold" = "regular") {
  if (textWidth(text, size, font) <= max) return text;
  let t = text;
  while (t.length > 1 && textWidth(`${t}…`, size, font) > max) t = t.slice(0, -1);
  return `${t}…`;
}

/**
 * The top of every page but the cover (SPEC §15.10c): the pattern's name in bold and "designer · ©" after it, then
 * `sub` (what the page is) smaller below. Both end before `max` points.
 */
export function drawHeader(page: PdfPage, box: PageBox, name: string, byline: string, sub: string, max = box.w - box.left - box.right) {
  const L = box.left, shown = fitText(name, 10, byline ? max * 0.6 : max, "bold");
  page.text("bold", 10, L, 24, shown);
  if (byline) {
    const x = L + textWidth(shown, 10, "bold");
    page.text("regular", 9, x, 24, fitText(` · ${byline}`, 9, max - (x - L)), "left", 0.35);
  }
  page.text("regular", 8, L, 36, fitText(sub, 8, max), "left", 0.35);
}

import { UA_BLUE, UA_YELLOW } from "@/core/flag";
import type { Palette, PaletteSlot } from "@/core/pattern/palette";
import type { Pattern } from "@/core/pattern/types";
import { rulerLabels } from "@/core/grid/numbering";
import { drawCells, drawGrid, drawLines, fullFrame, viewStyle, type ChartView } from "./chart";
import { drawKeyIcon } from "./keyIcon";
import { font, type CanvasTheme } from "./theme";

export interface KeyLine {
  slot: PaletteSlot;
  title: string;
  sub: string;
  count: number;
}

export interface ChartExportText {
  heading: string;
  /** Second heading line from pattern info, e.g. "Designer · ©" (SPEC §15.1). */
  byline?: string;
  key: KeyLine[];
  /** Symbols view only: entries whose symbols print in a colour (red, green, blue), as on the PDF's symbol chart. */
  symbolInks?: ReadonlyMap<PaletteSlot, string>;
  /** "Generated by пташечка · address · Glory to Ukraine", along the bottom edge; the flag is drawn after it. */
  footer?: string;
}

/** What a PNG shows: one of the chart views, or the preview with crosses drawn as embroidered thread. */
export type ImageView = ChartView | "stitched";

/**
 * PNG chart (SPEC §10.1). `view` "color" gives the small preview without grid numbers or key, "stitched" the same
 * with crosses as embroidered thread (bigger cells, so the thread shows); "both" / "symbols" give a printable chart
 * with the key underneath.
 */
export function renderChartImage(p: Pattern, palette: Palette, view: ImageView, theme: CanvasTheme, text: ChartExportText, cellSize?: number): HTMLCanvasElement {
  const stitched = view === "stitched", preview = view === "color" || stitched, ex = theme.export;
  const biggest = Math.max(p.w, p.h);
  const cells = stitched ? ex.stitchedCell : preview ? ex.previewCell : ex.chartCell, fit = stitched ? 3600 : preview ? 2400 : 4800;
  const z = cellSize ?? Math.max(cells[0], Math.min(cells[1], Math.floor(fit / biggest)));
  const M = cellSize ? 0 : preview ? ex.margin.preview : ex.margin.chart;
  const colW = ex.keyColumnWidth;
  const keyCols = Math.max(1, Math.floor((p.w * z + M * 2 - 40) / colW));
  const headerH = text.byline ? 22 : 0;
  const keyH = preview || cellSize ? 0 : 60 + headerH + Math.ceil(text.key.length / keyCols) * 34 + 40;
  const footerH = text.footer && !cellSize ? 28 : 0;
  const W = Math.max(p.w * z + M * 2, preview || cellSize ? 0 : colW + M * 2), H = p.h * z + M * 2 + keyH + footerH;
  const c = document.createElement("canvas");
  c.width = W;
  c.height = H;
  const g = c.getContext("2d")!;
  g.fillStyle = "#fff";
  g.fillRect(0, 0, W, H);
  const f = fullFrame(p, z, M, M), style = stitched ? { ...viewStyle("color", theme), stitched } : { ...viewStyle(view, theme), symbolInks: text.symbolInks };
  drawCells(g, p, palette, f, style);
  if (!preview) drawGrid(g, p, f, theme, view === "symbols", "rgba(0,0,0,.3)");
  drawLines(g, p, palette, f, style);
  if (cellSize) return c;
  if (text.footer) {
    g.fillStyle = ex.subText;
    g.font = font(theme, 400, 12);
    g.textAlign = "left";
    g.textBaseline = "middle";
    const y = H - footerH / 2 - (preview ? 2 : 8);
    g.fillText(text.footer, M, y);
    // the Ukrainian flag, drawn (no flag emoji on Windows)
    const x = M + g.measureText(text.footer).width + 6;
    g.fillStyle = UA_BLUE;
    g.fillRect(x, y - 5.5, 16, 5.5);
    g.fillStyle = UA_YELLOW;
    g.fillRect(x, y, 16, 5.5);
  }
  if (preview) return c;

  g.fillStyle = ex.subText;
  g.font = font(theme, 500, 13);
  g.textAlign = "center";
  g.textBaseline = "middle";
  const size = { w: p.w, h: p.h };
  for (const l of rulerLabels(p.grid, "x", size, 10)) g.fillText(String(l.text), M + l.at * z, M / 2);
  for (const l of rulerLabels(p.grid, "y", size, 10)) g.fillText(String(l.text), M / 2, M + l.at * z);
  g.fillStyle = theme.accent;
  const cx = M + (p.w * z) / 2, cy = M + (p.h * z) / 2;
  g.beginPath(); g.moveTo(cx - 7, M - 12); g.lineTo(cx + 7, M - 12); g.lineTo(cx, M - 2); g.fill();
  g.beginPath(); g.moveTo(M - 12, cy - 7); g.lineTo(M - 12, cy + 7); g.lineTo(M - 2, cy); g.fill();

  let ky = M + p.h * z + 40;
  g.textAlign = "left";
  g.fillStyle = ex.text;
  g.font = `600 20px Fraunces, serif`;
  g.fillText(text.heading, M, ky);
  if (text.byline) {
    ky += 22;
    g.font = font(theme, 400, 13);
    g.fillStyle = ex.subText;
    g.fillText(text.byline, M, ky);
  }
  ky += 36;
  text.key.forEach((r, k) => {
    const kx = M + (k % keyCols) * colW, yy = ky + Math.floor(k / keyCols) * 34;
    g.save();
    g.translate(kx, yy - 13);
    drawKeyIcon(g, r.slot, 26, view, theme, p.fabric, text.symbolInks);
    g.restore();
    g.strokeStyle = "#333";
    g.lineWidth = 1;
    g.strokeRect(kx + 0.5, yy - 12.5, 26, 26);
    g.textAlign = "left";
    g.textBaseline = "middle";
    g.fillStyle = ex.text;
    g.font = font(theme, 600, 13.5);
    g.fillText(r.title, kx + 34, yy - 6);
    g.font = font(theme, 400, 12);
    g.fillStyle = ex.subText;
    const sub = `${r.sub}  (${r.count})`;
    g.fillText(sub.length > 58 ? sub.slice(0, 57) + "…" : sub, kx + 34, yy + 9);
  });
  return c;
}
